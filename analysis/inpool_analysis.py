"""In-pool analysis of the whole-repo rerank run (rerank_v2.jsonl).

Question: separating pool construction from reranker quality. Restrict to instances whose
gold file is inside the rerank candidate pool (BM25 top-25 for every row of this run), then
compare every method by its rank of the gold file *within that pool*:
  - bm25: its own pool order (pool == bm25[:25], so the in-pool rank == whole-repo rank)
  - nami_bpt / nami_bits / qlm / h_real: their pool orderings (as stored)
  - dense_inpool: MiniLM whole-repo order filtered to pool files (dense reranking the same pool)
Also reports the pool-miss instances (gold outside pool) and where dense ranks them.
Stats: exact two-sided McNemar on top-k hits vs BM25; paired Wilcoxon signed-rank (normal approx,
tie-corrected) on reciprocal rank vs BM25; bootstrap 95% CI on top-k (10k, seed 20261107).
Usage (release root): python analysis/inpool_analysis.py [data/orderings_wholerepo.jsonl] [out.md] [pool_key]
pool_key: the ordering whose items define the rerank pool (default nami_bpt = the BM25 top-25 pool of the paper run).
"""
import json, math, sys, random
from math import comb

PATH = sys.argv[1] if len(sys.argv) > 1 else "data/orderings_wholerepo.jsonl"
OUT = sys.argv[2] if len(sys.argv) > 2 else "INPOOL_ANALYSIS.md"
POOL_KEY = sys.argv[3] if len(sys.argv) > 3 else "nami_bpt"
KS = (1, 3, 5, 10)
METHODS = ["bm25", "dense_inpool", "nami_bpt", "nami_bits", "qlm", "h_real"]

def load(path):
    latest = {}
    for line in open(path, encoding="utf-8"):
        try:
            r = json.loads(line)
        except Exception:
            continue
        if r.get("error") or r.get("skip_reason"):
            continue
        latest[r["instance"]] = r  # keep latest ok row per instance
    return list(latest.values())

def golds(r):
    g = r["gold"]
    return set(g if isinstance(g, list) else [g])

def rank_in(order, gs):
    for i, f in enumerate(order, 1):
        if f in gs:
            return i
    return None

def mcnemar(a_hits, b_hits):
    b = sum(1 for x, y in zip(a_hits, b_hits) if x and not y)  # method wins
    c = sum(1 for x, y in zip(a_hits, b_hits) if y and not x)  # bm25 wins
    n = b + c
    if n == 0:
        return b, c, 1.0
    k = min(b, c)
    p = min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)
    return b, c, p

def wilcoxon(x, y):
    d = [a - b for a, b in zip(x, y) if a != b]
    n = len(d)
    if n == 0:
        return 1.0
    absd = sorted((abs(v), i) for i, v in enumerate(d))
    ranks = [0.0] * n
    i = 0; tie_term = 0
    while i < n:
        j = i
        while j + 1 < n and absd[j + 1][0] == absd[i][0]:
            j += 1
        avg = (i + j) / 2 + 1
        for t in range(i, j + 1):
            ranks[absd[t][1]] = avg
        cnt = j - i + 1; tie_term += cnt ** 3 - cnt
        i = j + 1
    wplus = sum(rk for rk, v in zip(ranks, d) if v > 0)
    mu = n * (n + 1) / 4
    sd = math.sqrt(n * (n + 1) * (2 * n + 1) / 24 - tie_term / 48)
    if sd == 0:
        return 1.0
    z = (wplus - mu) / sd
    return math.erfc(abs(z) / math.sqrt(2))

def boot_ci(hits, n_boot=10000, seed=20261107):
    rng = random.Random(seed); n = len(hits)
    vals = sorted(sum(hits[rng.randrange(n)] for _ in range(n)) / n for _ in range(n_boot))
    return vals[int(0.025 * n_boot)], vals[int(0.975 * n_boot) - 1]

rows = load(PATH)
inp, miss = [], []
for r in rows:
    pool = r["orders"][POOL_KEY]  # pool order set (all rerankers share it)
    gs = golds(r)
    if not (gs & set(pool)):
        miss.append(r); continue
    pool_set = set(pool)
    rk = {"bm25": rank_in(r["orders"]["bm25"][:len(pool)], gs)}
    for m in ("nami_bpt", "nami_bits", "qlm", "h_real"):
        rk[m] = rank_in(r["orders"][m], gs)
    dense_pool = [f for f in r["orders"]["dense"] if f in pool_set]
    rk["dense_inpool"] = rank_in(dense_pool, gs)
    # dense top-100 dump may not contain every pool file; unseen pool files go to the bottom
    if rk["dense_inpool"] is None:
        rk["dense_inpool"] = len(pool)
    r["_rk"] = rk; inp.append(r)

N = len(inp)
lines = []
P = lines.append
P(f"# In-pool analysis — whole-repo rerank run (auto-generated by analysis/inpool_analysis.py)\n")
P(f"Source: `{PATH}` · {len(rows)} instances with ok rows · rerank pool = the files in orders[{POOL_KEY!r}].\n")
P(f"**Gold in pool: {N}/{len(rows)} ({100*N/len(rows):.0f}%). Pool misses: {len(miss)}.**\n")
P("## A. Reranking the same pool (gold-in-pool instances only)\n")
P("Every method ranks the identical 25 candidate files. `dense_inpool` = MiniLM whole-repo order "
  "restricted to the pool. McNemar = (+method wins / −BM25 wins, exact p); Wilcoxon on reciprocal rank vs BM25.\n")
P("| method | MRR | mean rank | " + " | ".join(f"top-{k}" for k in KS) + " | top-5 vs BM25 | Wilcoxon RR p |")
P("|---|---|---|" + "---|" * len(KS) + "---|---|")
bm_rr = [1 / r["_rk"]["bm25"] for r in inp]
for m in METHODS:
    rks = [r["_rk"][m] for r in inp]
    rr = [1 / x for x in rks]
    cells = []
    for k in KS:
        hits = [x <= k for x in rks]
        lo, hi = boot_ci(hits)
        cells.append(f"{sum(hits)}/{N} ({100*sum(hits)/N:.0f}%) [{100*lo:.0f},{100*hi:.0f}]")
    if m == "bm25":
        mc, wp = "—", "—"
    else:
        b, c, p = mcnemar([x <= 5 for x in rks], [r["_rk"]["bm25"] <= 5 for r in inp])
        mc = f"+{b}/−{c}, p={p:.3f}"
        wp = f"{wilcoxon(rr, bm_rr):.4f}"
    P(f"| {m} | {sum(rr)/N:.3f} | {sum(rks)/N:.1f} | " + " | ".join(cells) + f" | {mc} | {wp} |")

P("\n## B. Head-to-head inside the pool (instances where the method beats BM25's rank)\n")
for m in METHODS[1:]:
    better = [r for r in inp if r["_rk"][m] < r["_rk"]["bm25"]]
    worse = [r for r in inp if r["_rk"][m] > r["_rk"]["bm25"]]
    P(f"- **{m}**: better on {len(better)}, worse on {len(worse)}, tied {N-len(better)-len(worse)}")
P("\nLargest likelihood-family rescues inside the pool (BM25 rank > 5 and some likelihood method ≤ 3):\n")
for r in sorted(inp, key=lambda r: -r["_rk"]["bm25"]):
    k = r["_rk"]
    best = min(("nami_bpt", "nami_bits", "qlm"), key=lambda m: k[m])
    if k["bm25"] > 5 and k[best] <= 3:
        P(f"- {r['instance']}: bm25 {k['bm25']} → {best} {k[best]} (bpt {k['nami_bpt']}, bits {k['nami_bits']}, "
          f"qlm {k['qlm']}, dense_inpool {k['dense_inpool']})")

P("\n## C. Pool misses (gold outside BM25 top-25) — what a dense pool would have caught\n")
P("| instance | bm25 whole-repo rank | dense whole-repo rank |")
P("|---|---|---|")
dense_hits = {5: 0, 10: 0, 25: 0}
for r in sorted(miss, key=lambda r: r["ranks"]["dense"]):
    d = r["ranks"]["dense"]
    for k in dense_hits:
        dense_hits[k] += (0 < d <= k)
    P(f"| {r['instance']} | {r['ranks']['bm25']} | {d} |")
P(f"\nOf the {len(miss)} pool misses, dense ranks the gold file top-5 on {dense_hits[5]}, "
  f"top-10 on {dense_hits[10]}, top-25 on {dense_hits[25]}.\n")

P("## D. Data-quality flags\n")
for r in inp:
    k = r["_rk"]
    if all(k[m] == len(r["orders"][POOL_KEY]) for m in ("nami_bpt", "nami_bits", "qlm")):
        P(f"- {r['instance']}: gold ranked DEAD LAST by nami_bpt, nami_bits AND qlm (h_real {k['h_real']}, bm25 {k['bm25']}) "
          "— check that the gold file's chunks were scored (possible chunker/truncation artefact).")
P("\n_All numbers computed from the artifact by the script above; rerun after the final rows land._\n")

open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print("\n".join(lines))
